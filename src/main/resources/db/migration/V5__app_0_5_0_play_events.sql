-- Listening events for 0.5.0.
-- Does not update or delete existing library rows.
-- Stats stay instance-wide. A nullable user column can be added in 0.8
-- without rewriting these rows; this migration does not add one.

CREATE TABLE play_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audio_id INTEGER NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    listened_seconds INTEGER NOT NULL,
    completed BOOLEAN NOT NULL,
    counted BOOLEAN NOT NULL,
    source TEXT,
    playlist_id INTEGER,
    client_event_id TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT play_events_listened_seconds_check CHECK (listened_seconds >= 0),
    CONSTRAINT play_events_source_check CHECK (
        source IS NULL
        OR source IN ('library', 'search', 'playlist', 'artist', 'shuffle', 'other')
    ),
    CONSTRAINT play_events_audio_fk FOREIGN KEY (audio_id) REFERENCES audio_data (id) ON DELETE CASCADE,
    CONSTRAINT play_events_playlist_fk FOREIGN KEY (playlist_id) REFERENCES playlists (id) ON DELETE SET NULL,
    CONSTRAINT play_events_client_event_id_key UNIQUE (client_event_id)
);

CREATE INDEX play_events_started_at_idx ON play_events (started_at);
CREATE INDEX play_events_audio_id_idx ON play_events (audio_id);
