-- Typed tags (0.4.1). Existing tag rows become type "free".
-- Does not rewrite audio title, secondary_title, artist, album or name.

CREATE TABLE tag_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_key VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    is_system BOOLEAN NOT NULL,
    color VARCHAR(32),
    CONSTRAINT tag_types_type_key_key UNIQUE (type_key)
);

INSERT INTO tag_types (type_key, name, is_system) VALUES
    ('artist', 'Artista', TRUE),
    ('genre', 'Género', TRUE),
    ('album', 'Álbum', TRUE),
    ('year', 'Año', TRUE),
    ('language', 'Idioma', TRUE),
    ('free', 'Libre', TRUE);

