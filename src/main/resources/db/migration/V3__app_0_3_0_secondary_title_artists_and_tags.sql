CREATE INDEX audio_data_artist_idx ON audio_data (artist);

CREATE TABLE tags (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    name_key VARCHAR(100) NOT NULL,
    CONSTRAINT tags_name_key_key UNIQUE (name_key)
);

CREATE TABLE artists (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(500) NOT NULL,
    CONSTRAINT artists_name_key UNIQUE (name)
);

-- Copies distinct artist strings. Leaves every existing audio_data value as it is.
INSERT INTO artists (name)
SELECT DISTINCT artist
FROM audio_data
WHERE artist IS NOT NULL
  AND btrim(artist) <> '';

CREATE TABLE audio_tags (
    audio_id INTEGER NOT NULL,
    tag_id INTEGER NOT NULL,
    CONSTRAINT audio_tags_pkey PRIMARY KEY (audio_id, tag_id),
    CONSTRAINT audio_tags_audio_fk FOREIGN KEY (audio_id) REFERENCES audio_data (id),
    CONSTRAINT audio_tags_tag_fk FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE INDEX audio_tags_tag_idx ON audio_tags (tag_id);

CREATE TABLE artist_tags (
    artist_id INTEGER NOT NULL,
    tag_id INTEGER NOT NULL,
    CONSTRAINT artist_tags_pkey PRIMARY KEY (artist_id, tag_id),
    CONSTRAINT artist_tags_artist_fk FOREIGN KEY (artist_id) REFERENCES artists (id),
    CONSTRAINT artist_tags_tag_fk FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE INDEX artist_tags_tag_idx ON artist_tags (tag_id);

CREATE TABLE playlist_tags (
    playlist_id INTEGER NOT NULL,
    tag_id INTEGER NOT NULL,
    CONSTRAINT playlist_tags_pkey PRIMARY KEY (playlist_id, tag_id),
    CONSTRAINT playlist_tags_playlist_fk FOREIGN KEY (playlist_id) REFERENCES playlists (id),
    CONSTRAINT playlist_tags_tag_fk FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE INDEX playlist_tags_tag_idx ON playlist_tags (tag_id);
