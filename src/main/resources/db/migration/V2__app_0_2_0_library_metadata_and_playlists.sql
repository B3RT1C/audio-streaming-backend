CREATE TABLE playlists (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE playlist_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id INTEGER NOT NULL,
    audio_id INTEGER NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT playlist_items_playlist_fk FOREIGN KEY (playlist_id) REFERENCES playlists (id) ON DELETE CASCADE,
    CONSTRAINT playlist_items_audio_fk FOREIGN KEY (audio_id) REFERENCES audio_data (id) ON DELETE CASCADE,
    CONSTRAINT playlist_items_audio_unique UNIQUE (playlist_id, audio_id)
);

CREATE INDEX playlist_items_order_idx ON playlist_items (playlist_id, sort_order);
