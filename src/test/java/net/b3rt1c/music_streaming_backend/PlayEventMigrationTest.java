package net.b3rt1c.music_streaming_backend;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import org.junit.jupiter.api.Test;

class PlayEventMigrationTest {

    @Test
    void addsPlayEventsWithoutRewritingLibraryRows() throws Exception {
        try (Connection connection = open("play-events")) {
            try (Statement statement = connection.createStatement()) {
                statement.execute("""
                    CREATE TABLE audio_data (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(500) NOT NULL,
                        storage_key VARCHAR(255) NOT NULL UNIQUE,
                        extension VARCHAR(255) NOT NULL,
                        path VARCHAR(4096) NOT NULL,
                        title VARCHAR(500) NOT NULL,
                        secondary_title VARCHAR(500),
                        artist VARCHAR(500)
                    )
                    """);
                statement.execute("""
                    CREATE TABLE playlists (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(255) NOT NULL
                    )
                    """);
                statement.executeUpdate("""
                    INSERT INTO audio_data (name, storage_key, extension, path, title, secondary_title, artist)
                    VALUES ('n1', 'k1', 'mp3', 'uploads/songs/', 'Canción', 'Other', 'José')
                    """);
                statement.executeUpdate("INSERT INTO playlists (name) VALUES ('Noche')");
            }

            run(connection, "/db/migration/V5__app_0_5_0_play_events.sql");

            try (Statement statement = connection.createStatement()) {
                assertEquals("Canción", scalar(statement, "SELECT title FROM audio_data"));
                assertEquals("Other", scalar(statement, "SELECT secondary_title FROM audio_data"));
                assertEquals("José", scalar(statement, "SELECT artist FROM audio_data"));
                assertEquals("n1", scalar(statement, "SELECT name FROM audio_data"));
                assertEquals(1, count(statement, "SELECT COUNT(*) FROM audio_data"));
                assertEquals(1, count(statement, "SELECT COUNT(*) FROM playlists"));
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM play_events"));

                int audioId = count(statement, "SELECT id FROM audio_data");
                int playlistId = count(statement, "SELECT id FROM playlists");
                statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted, source, playlist_id)
                    VALUES (%d, CURRENT_TIMESTAMP, 40, FALSE, TRUE, 'library', %d)
                    """.formatted(audioId, playlistId));
                statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted)
                    VALUES (%d, CURRENT_TIMESTAMP, 0, FALSE, FALSE)
                    """.formatted(audioId));
                statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted, client_event_id)
                    VALUES (%d, CURRENT_TIMESTAMP, 1, FALSE, FALSE, NULL)
                    """.formatted(audioId));
                statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted, client_event_id)
                    VALUES (%d, CURRENT_TIMESTAMP, 1, FALSE, FALSE, 'same')
                    """.formatted(audioId));
                assertThrows(SQLException.class, () -> statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted, client_event_id)
                    VALUES (%d, CURRENT_TIMESTAMP, 1, FALSE, FALSE, 'same')
                    """.formatted(audioId)));
                assertThrows(SQLException.class, () -> statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted)
                    VALUES (%d, CURRENT_TIMESTAMP, -1, FALSE, FALSE)
                    """.formatted(audioId)));
                assertThrows(SQLException.class, () -> statement.executeUpdate("""
                    INSERT INTO play_events (audio_id, started_at, listened_seconds, completed, counted, source)
                    VALUES (%d, CURRENT_TIMESTAMP, 1, FALSE, FALSE, 'radio')
                    """.formatted(audioId)));

                statement.executeUpdate("DELETE FROM playlists");
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM play_events WHERE playlist_id IS NOT NULL"));
                assertTrue(count(statement, "SELECT COUNT(*) FROM play_events") > 0);
                assertNull(scalar(statement, "SELECT playlist_id FROM play_events WHERE listened_seconds = 40"));

                statement.executeUpdate("DELETE FROM audio_data");
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM play_events"));
            }
        }
    }

    @Test
    void migrationDoesNotTouchExistingRows() throws Exception {
        String sql = new String(
            PlayEventMigrationTest.class.getResourceAsStream("/db/migration/V5__app_0_5_0_play_events.sql").readAllBytes(),
            StandardCharsets.UTF_8
        ).toLowerCase().replaceAll("(?m)--.*$", "");
        assertFalse(sql.contains("update "));
        assertFalse(sql.contains("delete from"));
        assertFalse(sql.contains("drop table"));
        assertFalse(sql.contains("user_id"));
        assertFalse(sql.contains("title"));
        assertTrue(sql.contains("create table play_events"));
        assertTrue(sql.contains("on delete cascade"));
        assertTrue(sql.contains("on delete set null"));
        assertTrue(sql.contains("listened_seconds >= 0"));
        assertTrue(sql.contains("play_events_started_at_idx"));
        assertTrue(sql.contains("play_events_audio_id_idx"));
    }

    private static Connection open(String name) throws Exception {
        return DriverManager.getConnection(
            "jdbc:h2:mem:" + name + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1",
            "sa",
            ""
        );
    }

    private static void run(Connection connection, String resource) throws Exception {
        String sql = new String(
            PlayEventMigrationTest.class.getResourceAsStream(resource).readAllBytes(),
            StandardCharsets.UTF_8
        );
        StringBuilder statementText = new StringBuilder();
        for (String line : sql.split("\n")) {
            String trimmed = line.trim();
            if (trimmed.startsWith("--")) {
                continue;
            }
            statementText.append(line).append('\n');
            if (trimmed.endsWith(";")) {
                String command = statementText.toString().trim();
                command = command.substring(0, command.length() - 1);
                try (Statement statement = connection.createStatement()) {
                    statement.execute(command);
                }
                statementText.setLength(0);
            }
        }
    }

    private static int count(Statement statement, String sql) throws Exception {
        try (ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getInt(1);
        }
    }

    private static String scalar(Statement statement, String sql) throws Exception {
        try (ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getString(1);
        }
    }
}
