package net.b3rt1c.music_streaming_backend;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import org.junit.jupiter.api.Test;

class ArtistBackfillMigrationTest {

    @Test
    void copiesDistinctArtistsWithoutRewritingTracks() throws Exception {
        try (Connection connection = open("backfill")) {
            migrateThroughV2(connection);
            try (Statement statement = connection.createStatement()) {
                statement.executeUpdate("""
                    INSERT INTO audio_data (name, storage_key, extension, path, title, artist)
                    VALUES
                      ('t1', 'k1', 'mp3', 'uploads/songs/', 'Canción', 'José'),
                      ('t2', 'k2', 'mp3', 'uploads/songs/', 'Otra', 'José'),
                      ('t3', 'k3', 'mp3', 'uploads/songs/', 'Lower', 'jose'),
                      ('t4', 'k4', 'mp3', 'uploads/songs/', 'Vacio', NULL),
                      ('t5', 'k5', 'mp3', 'uploads/songs/', 'Blancos', '   '),
                      ('t6', 'k6', 'mp3', 'uploads/songs/', 'Espacio', 'Ana ')
                    """);
            }
            run(connection, "/db/migration/V3__app_0_3_0_secondary_title_artists_and_tags.sql");

            try (Statement statement = connection.createStatement()) {
                assertEquals(6, count(statement, "SELECT COUNT(*) FROM audio_data"));
                assertEquals(3, count(statement, "SELECT COUNT(*) FROM artists"));
                assertEquals("José", scalar(statement, "SELECT artist FROM audio_data WHERE storage_key = 'k1'"));
                assertEquals("jose", scalar(statement, "SELECT artist FROM audio_data WHERE storage_key = 'k3'"));
                assertEquals("   ", scalar(statement, "SELECT artist FROM audio_data WHERE storage_key = 'k5'"));
                assertEquals("Ana ", scalar(statement, "SELECT artist FROM audio_data WHERE storage_key = 'k6'"));
                assertEquals("Canción", scalar(statement, "SELECT title FROM audio_data WHERE storage_key = 'k1'"));
                assertEquals("t1", scalar(statement, "SELECT name FROM audio_data WHERE storage_key = 'k1'"));
                assertNull(scalar(statement, "SELECT secondary_title FROM audio_data WHERE storage_key = 'k1'"));
                assertEquals(1, count(statement, "SELECT COUNT(*) FROM artists WHERE name = 'José'"));
                assertEquals(1, count(statement, "SELECT COUNT(*) FROM artists WHERE name = 'jose'"));
                assertEquals(1, count(statement, "SELECT COUNT(*) FROM artists WHERE name = 'Ana '"));
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM artists WHERE btrim(name) = ''"));
            }
        }
    }

    @Test
    void emptyLibraryStillMigrates() throws Exception {
        try (Connection connection = open("backfill-empty")) {
            migrateThroughV2(connection);
            run(connection, "/db/migration/V3__app_0_3_0_secondary_title_artists_and_tags.sql");
            try (Statement statement = connection.createStatement()) {
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM artists"));
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM tags"));
                assertEquals(0, count(statement, "SELECT COUNT(*) FROM audio_data"));
            }
        }
    }

    @Test
    void migrationDoesNotUpdateExistingAudioRows() throws Exception {
        String sql = new String(
            ArtistBackfillMigrationTest.class.getResourceAsStream(
                "/db/migration/V3__app_0_3_0_secondary_title_artists_and_tags.sql"
            ).readAllBytes(),
            StandardCharsets.UTF_8
        ).toLowerCase().replaceAll("(?m)--.*$", "");
        assertFalse(sql.contains("update "));
        assertFalse(sql.contains("drop "));
        assertFalse(sql.contains("delete "));
        assertTrue(sql.contains("insert into artists"));
        assertTrue(sql.contains("secondary_title"));
    }

    private static void migrateThroughV2(Connection connection) throws Exception {
        // V2 adds several columns in one ALTER TABLE, which PostgreSQL accepts and H2 does not.
        // Build the same pre-0.3.0 shape here, then execute the real V3 script.
        try (Statement statement = connection.createStatement()) {
            statement.execute("""
                CREATE TABLE audio_data (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(500) NOT NULL,
                    storage_key VARCHAR(255) NOT NULL UNIQUE,
                    extension VARCHAR(255) NOT NULL,
                    path VARCHAR(4096) NOT NULL,
                    content_hash VARCHAR(255),
                    title VARCHAR(500) NOT NULL,
                    artist VARCHAR(500),
                    album VARCHAR(500),
                    duration_seconds INTEGER,
                    track_number INTEGER,
                    original_filename VARCHAR(500),
                    original_path VARCHAR(4096),
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
            statement.execute("""
                CREATE TABLE playlists (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(255) NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        }
    }

    private static Connection open(String name) throws Exception {
        return DriverManager.getConnection(
            "jdbc:h2:mem:" + name + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1",
            "sa",
            ""
        );
    }

    private static void run(Connection connection, String resource) throws Exception {
        String sql = new String(
            ArtistBackfillMigrationTest.class.getResourceAsStream(resource).readAllBytes(),
            StandardCharsets.UTF_8
        );
        StringBuilder statementText = new StringBuilder();
        for (String line : sql.split("\n")) {
            String trimmed = line.trim();
            if (trimmed.startsWith("--")) {
                continue;
            }
            statementText.append(line).append('\n');
            if (trimmed.endsWith(";")) {
                String command = statementText.toString().trim();
                command = command.substring(0, command.length() - 1);
                try (Statement statement = connection.createStatement()) {
                    statement.execute(command);
                }
                statementText.setLength(0);
            }
        }
    }

    private static int count(Statement statement, String sql) throws Exception {
        try (ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getInt(1);
        }
    }

    private static String scalar(Statement statement, String sql) throws Exception {
        try (ResultSet rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getString(1);
        }
    }
}
